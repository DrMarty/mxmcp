"""Generate docs/CLI_REGISTRY.md from analysis/cli_registry.json.

The registry is the complete set of command strings CubeMX registers at runtime
(app jar + every plugin/ip jar), with the declaring class, arity and help text.
Keeping the markdown generated means it cannot drift from the evidence.
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SRC = HERE / "analysis" / "cli_registry.json"
DST = HERE / "docs" / "CLI_REGISTRY.md"


def main() -> int:
    rows = json.loads(SRC.read_text(encoding="utf-8"))
    by_head: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        head = (r["command"] or "?").split()[0]
        by_head[head].append(r)
    jars = sorted({r["jar"] for r in rows})
    out: list[str] = []
    out.append("# CubeMX CLI registry (complete)\n")
    out.append("Generated by `tools/make_cli_registry_md.py` from "
               "`analysis/cli_registry.json`, which is extracted by "
               "`tools/dump_cli_registry.py` (constant-pool scan of every "
               "`CommandLineManager.addCommand(...)` call site in the rebuilt "
               f"application jar and in all plugin jars). {len(rows)} unique "
               f"registrations across {len(jars)} jars.\n")
    out.append("`argc` is the number of arguments the dispatcher expects "
               "(`0` means the bare command runs). Commands whose name is built "
               "at runtime (`<IP> <verb>`, e.g. `NVIC enable`) appear with the "
               "template they are built from.\n")
    out.append("## Command heads\n")
    out.append("| head | sub-commands | registered by |")
    out.append("|---|---|---|")
    for head in sorted(by_head):
        owners = sorted({r["registrar"].rsplit(".", 1)[-1] for r in by_head[head]})
        out.append(f"| `{head}` | {len(by_head[head])} | {', '.join(owners[:4])}"
                   f"{' …' if len(owners) > 4 else ''} |")
    out.append("")
    for head in sorted(by_head):
        out.append(f"## `{head}`\n")
        for r in sorted(by_head[head], key=lambda x: x["command"]):
            argc = "?" if r["argc"] is None else r["argc"]
            help_txt = (r["help"] or "").replace("\n", " ").strip()
            out.append(f"- **`{r['command']}`** · argc={argc} · "
                       f"`{r['jar']}` → `{r['registrar']}.{r['registrar_method']}`")
            if help_txt:
                out.append(f"  \n  {help_txt[:400]}")
        out.append("")
    DST.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {DST.name}: {len(rows)} commands, {len(by_head)} heads, "
          f"{DST.stat().st_size} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
